// Helper to check if a date is a holiday or weekend (Friday/Saturday)
export function getDayType(dateStr: string): {
  isWeekend: boolean;
  isHoliday: boolean;
  holidayTitle?: string;
} {
  const d = new Date(dateStr + "T00:00:00");
  const dayOfWeek = d.getDay(); // 0 = Sunday, 5 = Friday, 6 = Saturday
  const isWeekend = dayOfWeek === 5 || dayOfWeek === 6;

  const foundHoliday = ACADEMIC_HOLIDAYS_2026.find((h) => h.date === dateStr);
  return {
    isWeekend,
    isHoliday: !!foundHoliday,
    holidayTitle: foundHoliday ? foundHoliday.titleBangla : undefined,
  };
}

