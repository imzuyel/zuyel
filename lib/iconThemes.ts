export function getThemedIconStyle(
  itemId: string,
  iconTheme: IconThemeId = "rainbow",
  animationLevel: IconAnimationLevel = "vibrant"
): ThemedIconStyle {
  const itemConfig = MODULE_COLOR_MAP[itemId];
  const fallbackDynamic = FALLBACK_COLOR_PALETTES[getHashIndex(itemId, FALLBACK_COLOR_PALETTES.length)];
  let style: ThemedIconStyle =
    (itemConfig && (itemConfig as any)[iconTheme]) ||
    fallbackDynamic ||
    DEFAULT_THEME_STYLES[iconTheme] ||
    DEFAULT_THEME_STYLES.rainbow;

  if (animationLevel === "none") {
    return {
      ...style,
      animClass: "transition-none",
    };
  }

  if (animationLevel === "subtle") {
    return {
      ...style,
      animClass: "group-hover:scale-110 transition-transform duration-200",
    };
  }

  return style;
}
