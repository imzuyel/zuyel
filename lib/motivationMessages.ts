// Helper to get a random message from a category, using player context to make it feel deterministic yet dynamic
export function getRandomMotivationMessage(category: string, playerSeed: string): string {
  const messages = MOTIVATION_MESSAGES[category] || MOTIVATION_MESSAGES["MEDIUM"];
  // Deterministic selection based on seed to prevent message changes on refresh
  let hash = 0;
  for (let i = 0; i < playerSeed.length; i++) {
    hash = playerSeed.charCodeAt(i) + ((hash << 5) - hash);
  }
  const index = Math.abs(hash) % messages.length;
  return messages[index];
}
